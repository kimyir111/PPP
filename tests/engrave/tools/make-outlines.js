/* G04 §16.3, §18.2, G4c: the glyph outlines the SVG backend draws, taken once from the pinned font data.

     node tests/engrave/tools/make-outlines.js           write engrave/outlines.js
     node tests/engrave/tools/make-outlines.js --check   exit 1 if engrave/outlines.js holds other outlines

   The Bravura outlines of vendor/vexflow-4.2.3.js for every glyph engrave/metrics.js names (make-metrics.js NAMES), as
   SVG path data in the font's own integer units, y up. VexFlow keeps outlines at 1.44 times the units of its bounding
   boxes (a font unit of the boxes is 4 / resolution sp, of the outlines 4 / (1.44 * resolution) = 1/360 sp), so the
   backend draws them with scale(1/360, -1/360): exactly the size engrave/metrics.js lays out (the G4b review R7 found
   the development view drawing them 1.44 times too large). VexFlow writes a curve's end point before its control
   points; the path data here is in SVG order. Nothing at run time loads VexFlow. */
'use strict';
const fs = require('fs');
const path = require('path');
const { NAMES } = require('./make-metrics.js');

const REPO = path.resolve(__dirname, '..', '..', '..');
const FILE = path.join(REPO, 'engrave', 'outlines.js');
/* outline units per staff space: 1000 units an em in the boxes, 1.44 times that in the outlines, 4 sp an em */
const UNITS_PER_SP = 360;

function pathData(o) {
  const t = String(o).trim().split(/\s+/);
  const out = [];
  for (let i = 0; i < t.length;) {
    const c = t[i++];
    const P = (x, y) => Math.round(+x) + ' ' + Math.round(+y);
    if (c === 'm') { out.push('M' + P(t[i], t[i + 1])); i += 2; }
    else if (c === 'l') { out.push('L' + P(t[i], t[i + 1])); i += 2; }
    else if (c === 'q') { out.push('Q' + P(t[i + 2], t[i + 3]) + ' ' + P(t[i], t[i + 1])); i += 4; }
    else if (c === 'b') { out.push('C' + P(t[i + 2], t[i + 3]) + ' ' + P(t[i + 4], t[i + 5]) + ' ' + P(t[i], t[i + 1])); i += 6; }
    else if (c === 'z') out.push('Z');
    else throw new Error('outline command ' + c);
  }
  return out.join('');
}

function build() {
  const m = require(path.join(REPO, 'vendor', 'vexflow-4.2.3.js'));
  const VF = m.Flow || m;
  const font = VF.getMusicFontStack()[0];
  if (font.getName() !== 'Bravura') throw new Error('the first font of the pinned stack is ' + font.getName());
  if (font.getResolution() !== 1000) throw new Error('resolution ' + font.getResolution());
  const glyphs = font.getGlyphs();
  const lines = [];
  NAMES.forEach(n => {
    const g = glyphs[n];
    if (!g || !g.o) return;
    lines.push('    ' + JSON.stringify(n) + ': ' + JSON.stringify(pathData(g.o)));
  });
  return [
    '/* ============================================================================',
    '   PPP engrave — glyph outlines for the SVG backend (docs/GOALS/G04 §16.3, §18.2; G4c)',
    '',
    '   GENERATED by tests/engrave/tools/make-outlines.js from the pinned VexFlow',
    '   4.2.3 build (vendor/vexflow-4.2.3.js); `--check` runs in CI. Do not edit.',
    '',
    '   The outlines of the Bravura font, (c) Steinberg Media Technologies GmbH,',
    '   SIL Open Font License 1.1 (vendor/LICENSE-bravura-OFL.txt, vendor/README.md),',
    '   unchanged: SVG path data in font units, y up. One staff space is UNITS',
    '   units, so svg.js draws a glyph with scale(1/UNITS, -1/UNITS) - the size',
    '   engrave/metrics.js lays out.',
    '   ========================================================================== */',
    '(function (root, factory) {',
    "  'use strict';",
    "  if (typeof module === 'object' && module.exports) module.exports = factory();",
    '  else (root.PPPEngraveModules = root.PPPEngraveModules || {}).outlines = factory();',
    "})(typeof globalThis !== 'undefined' ? globalThis : this, function () {",
    "  'use strict';",
    '  const UNITS = ' + UNITS_PER_SP + ';',
    '  const PATHS = Object.freeze({',
    lines.join(',\n'),
    '  });',
    '  return Object.freeze({ UNITS, PATHS });',
    '});',
    ''].join('\n');
}

if (require.main === module) {
  const next = build();
  if (process.argv.indexOf('--check') > 0) {
    const cur = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8').replace(/\r\n/g, '\n') : '';
    console.log(cur === next ? 'engrave/outlines.js holds the pinned font\'s outlines' : 'engrave/outlines.js DIFFERS from the pinned font');
    process.exit(cur === next ? 0 : 1);
  }
  fs.writeFileSync(FILE, next);
  console.log('wrote the outlines of ' + (next.match(/^\s{4}"/gm) || []).length + ' glyphs into engrave/outlines.js (' + next.length + ' bytes)');
}
module.exports = { build, pathData, UNITS_PER_SP };
